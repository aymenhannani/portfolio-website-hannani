(function (w, d) {

  var STRINGS = {};
  for (var k in I18N_EN) STRINGS[k] = { en: I18N_EN[k], fr: I18N_FR[k] || null };

  var current = d.documentElement.getAttribute("data-lang") === "fr" ? "fr" : "en";

  var valueOf = function (key, lang) {
    var entry = STRINGS[key];
    if (!entry) return null;
    return entry[lang] || entry.en;
  };

  /* Applies to any subtree, so freshly cloned <template> content is covered. */
  var translate = function (root, lang) {
    var nodes = root.querySelectorAll("[data-i18n]");
    for (var i = 0; i < nodes.length; i++) {
      var v = valueOf(nodes[i].getAttribute("data-i18n"), lang);
      if (v !== null && nodes[i].innerHTML !== v) nodes[i].innerHTML = v;
    }

    var attrNodes = root.querySelectorAll("[data-i18n-attr]");
    for (var j = 0; j < attrNodes.length; j++) {
      var pairs = attrNodes[j].getAttribute("data-i18n-attr").split(",");
      for (var p = 0; p < pairs.length; p++) {
        var bits = pairs[p].split(":");
        var av = valueOf(bits[1], lang);
        if (av !== null) attrNodes[j].setAttribute(bits[0], av);
      }
    }
  };

  w.I18N = {
    strings: STRINGS,

    lang: function () { return current; },

    /* single string lookup, for labels script.js builds at runtime */
    t: function (key) { return valueOf(key, current); },

    /* "6 projects" / "6 projets" — plural handled per language */
    count: function (n) {
      var key = n === 1 ? "portfolio.count.one" : "portfolio.count.other";
      var tpl = valueOf(key, current) || (n + " projects");
      return tpl.replace("{n}", n);
    },

    apply: function (root) { translate(root || d.body, current); },

    set: function (lang) {
      current = lang === "fr" ? "fr" : "en";
      d.documentElement.setAttribute("lang", current);
      d.documentElement.setAttribute("data-lang", current);
      try { localStorage.setItem("lang", current); } catch (e) { }
      translate(d.body, current);
      if (w.onLangChange) w.onLangChange(current);
      d.documentElement.classList.remove("i18n-cloak");
    },
  };

  /* first paint: the bootstrap in <head> already set data-lang */
  translate(d.body, current);
  d.documentElement.classList.remove("i18n-cloak");

})(window, document);
